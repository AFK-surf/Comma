import { format } from "prettier";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import * as icons from "@central-icons-react/round-outlined-radius-2-stroke-2";

// Reuse the Central glyph names recorded in ui/components/icons/iconRegistry.ts.
const names = {
  "go-comma-assistant": "IconHomeRoof",
  "go-inbox": "IconBox2",
  "go-drive": "IconFolder2",
  "drive-add-folder": "IconFolderAddRight",
  "drive-upload-folder": "IconFolderUpload",
  "go-tasks": "IconPlanning",
  "go-plugins": "IconPuzzle",
  "go-search": "IconMagnifyingGlass",
  "go-routines": "IconCalendarDays",
  "record-start": "IconMicrophone",
  "drive-upload": "IconCloudUpload",
  "drive-download": "IconArrowInbox",
  "browser-new-tab": "IconPlusLarge",
};
const images = {};
for (const [id, name] of Object.entries(names)) {
  const svg = renderToStaticMarkup(
    createElement(icons[name], { width: 32, height: 32, color: "black" })
  );
  images[id] = (
    await sharp(Buffer.from(svg), { density: 192 }).resize(32, 32).png().toBuffer()
  ).toString("base64");
}
await writeFile(
  new URL("../src/main/generated/application-menu-icons.ts", import.meta.url),
  await format(
    "// Generated by scripts/generate-menu-icons.mjs from the existing Central icon registry.\nexport const applicationMenuIcons: Record<string, string> = " +
      JSON.stringify(images, null, 2) +
      ";\n",
    { parser: "typescript" }
  )
);
