/**
 * The values the card tokens have in the design system's own themes, as the
 * stylesheet the runtime document carries. A host that resolves tokens for its
 * own theme (the desktop app) overrides them; a host that sends none (the
 * phone apps) shows the cards on these.
 */

/** `--name: value` declarations of every theme block whose selector is `selector`. */
function declarations(css, selector) {
  const found = new Map();
  let matched = false;
  const rules = css.replaceAll(/\/\*[\s\S]*?\*\//g, "");
  for (const [, name, body] of rules.matchAll(/([^{}]+)\{\n([^}]*)\n\}/g)) {
    if (name.trim().replaceAll(/\s+/g, " ") !== selector) continue;
    matched = true;
    for (const line of body.split("\n")) {
      const declaration = /^\s*(--[a-z0-9-]+):\s*(.+);\s*$/i.exec(line);
      if (declaration) found.set(declaration[1], declaration[2]);
    }
  }
  if (!matched) throw new Error(`theme.css has no block ${selector}`);
  return found;
}

/** sRGB hex to OKLCH lightness, chroma and alpha. */
function oklch(hex) {
  const digits = hex.slice(1);
  const channel = (index) => {
    const value = Number.parseInt(digits.slice(index * 2, index * 2 + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  };
  const [r, g, b] = [channel(0), channel(1), channel(2)];
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return {
    lightness: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    alpha: digits.length === 8 ? Number.parseInt(digits.slice(6, 8), 16) / 255 : 1,
  };
}

const round = (value, places) => Number(value.toFixed(places));

/**
 * A neutral the design system tints with the app theme's hue, as a fixed
 * color for the default theme: the hex's own lightness, the theme's chroma
 * scaled by that lightness, and the theme's hue.
 */
function tinted(value, theme) {
  const match = /^oklch\(from (#[0-9a-f]{6}(?:[0-9a-f]{2})?) /i.exec(value);
  if (!match) return value;
  const { lightness, alpha } = oklch(match[1]);
  const span = 4 * lightness * (1 - lightness);
  const lifted = Math.min(
    1,
    Math.max(0, lightness + (Math.min(0.64, Math.max(0.36, theme.l)) - 0.5) * span)
  );
  const color = `${round(lifted, 4)} ${round(theme.c * span, 4)} ${round(theme.h, 2)}`;
  return alpha < 1 ? `oklch(${color} / ${round(alpha, 3)})` : `oklch(${color})`;
}

/**
 * `:root` rules that give every name in `tokens` its light value, and its dark
 * value under `[data-comma-scheme=dark]` where that differs.
 */
export function renderCardTokenDefaults(themeCss, tokens) {
  const base = new Map([
    ...declarations(themeCss, "@theme static"),
    ...declarations(themeCss, ":root"),
    ...declarations(themeCss, ':root, [data-theme="Light mode"]'),
  ]);
  const light = new Map([
    ...base,
    ...declarations(themeCss, '[data-theme="Light mode"]'),
  ]);
  const dark = new Map([
    ...light,
    ...declarations(themeCss, '.dark, [data-theme="Dark mode"]'),
  ]);
  const number = (name) => Number.parseFloat(base.get(name) ?? "");
  const theme = {
    h: number("--comma-theme-h"),
    c: number("--comma-theme-c"),
    l: number("--comma-theme-l"),
  };
  if (!Object.values(theme).every(Number.isFinite))
    throw new Error("theme.css has no default theme hue, chroma and lightness");
  const resolve = (values, name, seen = []) => {
    const value = values.get(name);
    if (value === undefined) throw new Error(`theme.css has no ${name}`);
    if (seen.includes(name)) throw new Error(`${name} refers to itself`);
    return tinted(value, theme).replaceAll(/var\((--[a-z0-9-]+)\)/gi, (_, other) =>
      resolve(values, other, [...seen, name])
    );
  };
  const names = [...new Set(tokens)].toSorted();
  const lightRules = names.map((name) => `${name}:${resolve(light, name)}`);
  const darkRules = names
    .filter((name) => resolve(dark, name) !== resolve(light, name))
    .map((name) => `${name}:${resolve(dark, name)}`);
  return `:root{${lightRules.join(";")}}:root[data-comma-scheme=dark]{${darkRules.join(";")}}`;
}

/** The generated module's source. */
export function renderCardTokenDefaultsModule(themeCss, tokens) {
  return `// Generated by scripts/generate-card-token-defaults.mjs from packages/ui/src/styles/theme.css. Do not edit by hand.
export const cardTokenDefaults =
  ${JSON.stringify(renderCardTokenDefaults(themeCss, tokens))};
`;
}
