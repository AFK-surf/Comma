#!/usr/bin/env node

// The glyphs the card templates and <comma-icon> draw, as static SVG for a
// host that has no icon registry of its own (the phone apps). The desktop app
// renders the same glyphs from @comma/ui; packages/app's cardHost test fails
// when this file and that registry differ.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { IconAirplane } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconAirplane";
import { IconArrowRight } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconArrowRight";
import { IconArrowUp } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconArrowUp";
import { IconCarFrontView } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCarFrontView";
import { IconCheckmark1 } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCheckmark1";
import { IconCheckmark1Small } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCheckmark1Small";
import { IconChevronRightSmall } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconChevronRightSmall";
import { IconCircleInfo } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCircleInfo";
import { IconClock } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconClock";
import { IconCloud } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCloud";
import { IconCloudySun } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconCloudySun";
import { IconMoon } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconMoon";
import { IconRainy } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconRainy";
import { IconSend } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconSend";
import { IconShoppingBag3 } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconShoppingBag3";
import { IconSnowFlakes } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconSnowFlakes";
import { IconSun } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconSun";
import { IconTag } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconTag";
import { IconTrainFrontView } from "@central-icons-react/round-outlined-radius-2-stroke-2/IconTrainFrontView";

const icons = {
  sun: IconSun,
  moon: IconMoon,
  cloud: IconCloud,
  "partly-cloudy": IconCloudySun,
  rain: IconRainy,
  snow: IconSnowFlakes,
  check: IconCheckmark1Small,
  "check-large": IconCheckmark1,
  "arrow-up": IconArrowUp,
  "arrow-right": IconArrowRight,
  "chevron-right": IconChevronRightSmall,
  "shopping-bag": IconShoppingBag3,
  send: IconSend,
  tag: IconTag,
  train: IconTrainFrontView,
  airplane: IconAirplane,
  car: IconCarFrontView,
  clock: IconClock,
  info: IconCircleInfo,
};

// The props @comma/ui's createCentralIcon gives every glyph.
const markup = Object.fromEntries(
  Object.entries(icons).map(([name, Icon]) => [
    name,
    renderToStaticMarkup(
      createElement(Icon, { ariaHidden: true, "data-comma-icon": "", mode: "raw" })
    ),
  ])
);

const output = fileURLToPath(
  new URL("../src/dynamic-ui/cardIconDefaults.ts", import.meta.url)
);
writeFileSync(
  output,
  await format(
    `// Generated by scripts/generate-card-icon-defaults.mjs from Central Icons. Do not edit by hand.
export const cardIconDefaults: Record<string, string> = ${JSON.stringify(markup)};
`,
    { ...(await resolveConfig(output)), filepath: output }
  )
);
