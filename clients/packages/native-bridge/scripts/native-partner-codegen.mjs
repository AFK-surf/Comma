class SwiftRenderer {
  constructor(bundle) {
    this.definitions = bundle.$defs;
    this.declarations = new Map();
    this.protocolVersions = collectProtocolVersions(bundle.$defs);
  }

  register(name, schema, { allowUnversionedUnion = false } = {}) {
    if (this.declarations.has(name)) return name;
    if (!schema) throw new Error(`Missing JSON Schema for Swift type ${name}.`);

    this.declarations.set(name, "");
    if (schema.oneOf) {
      this.declarations.set(
        name,
        this.renderUnion(name, schema, allowUnversionedUnion)
      );
    } else if (schema.type === "object") {
      this.declarations.set(name, this.renderStruct(name, schema));
    } else if (
      schema.type === "string" &&
      (schema.enum || schema.const !== undefined)
    ) {
      this.declarations.set(
        name,
        this.renderStringEnum(name, schema.enum ?? [schema.const])
      );
    } else {
      throw new Error(`Unsupported top-level JSON Schema for Swift type ${name}.`);
    }
    return name;
  }

  render() {
    return `${[...this.declarations.values()].filter(Boolean).join("\n\n")}\n`;
  }

  ensureProtocolVersion() {
    if (this.declarations.has("CommaChatProtocolVersion")) return;
    this.declarations.set(
      "CommaChatProtocolVersion",
      `public enum CommaChatProtocolVersion: Int, Codable, Equatable, Sendable {
${this.protocolVersions.map((version) => `    case v${version} = ${version}`).join("\n")}
}`
    );
  }

  renderStruct(name, schema) {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([property, propertySchema]) =>
        this.field(name, property, propertySchema, required.has(property))
    );
    const declarations = fields.map(
      (field) => `    public let ${swiftMember(field.property)}: ${field.type}`
    );
    const parameters = fields.map((field) => {
      const defaultValue = field.constantCase
        ? ` = .${field.constantCase}`
        : field.required
          ? ""
          : " = nil";
      return `        ${swiftMember(field.property)}: ${field.type}${defaultValue}`;
    });
    const assignments = fields.map(
      (field) =>
        `        self.${swiftMember(field.property)} = ${swiftMember(field.property)}`
    );
    const codingKeys = fields.map(
      (field) => `        case ${swiftMember(field.property)} = "${field.property}"`
    );
    const decoding = fields.flatMap((field) => [
      `        self.${swiftMember(field.property)} = ${this.decodeExpression(field)}`,
      ...this.renderConstantDecodingValidation(
        field,
        `self.${swiftMember(field.property)}`
      ),
    ]);
    const encoding = fields.flatMap((field) => [
      ...this.renderConstantEncodingValidation(
        field,
        `self.${swiftMember(field.property)}`
      ),
      ...this.renderEncodingValidation(field),
      `        try container.${field.required ? "encode" : "encodeIfPresent"}(self.${swiftMember(field.property)}, forKey: .${swiftMember(field.property)})`,
    ]);

    return `public struct ${name}: Codable, Equatable, Sendable {
${declarations.join("\n")}

    public init(
${parameters.join(",\n")}
    ) {
${assignments.join("\n")}
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
${decoding.join("\n")}
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
${encoding.join("\n")}
    }

    private enum CodingKeys: String, CodingKey {
${codingKeys.join("\n")}
    }
}`;
  }

  renderStringEnum(name, values) {
    return `public enum ${name}: String, Codable, Equatable, Sendable {
${values.map((value) => `    case ${swiftCase(value)} = ${JSON.stringify(value)}`).join("\n")}
}`;
  }

  renderUnion(name, schema, allowUnversioned) {
    const variants = schema.oneOf.map((variant) =>
      this.variant(name, this.resolve(variant))
    );
    const versioned = variants.every(
      (variant) => variant.protocolVersion !== undefined
    );
    if (
      !versioned &&
      variants.some((variant) => variant.protocolVersion !== undefined)
    ) {
      throw new Error(
        `${name} must either version every union variant or leave every variant unversioned.`
      );
    }
    if (!versioned && !allowUnversioned) {
      throw new Error(
        `${name} top-level protocol variants must require a positive integer protocolVersion literal.`
      );
    }
    const allProperties = new Set(versioned ? ["kind", "protocolVersion"] : ["kind"]);
    for (const variant of variants) {
      for (const field of variant.fields) allProperties.add(field.property);
      for (const constant of variant.constants) allProperties.add(constant.property);
      for (const property of variant.forbidden) allProperties.add(property);
    }
    const orderedKeys = [...allProperties].toSorted((left, right) => {
      const priority = { kind: 0, protocolVersion: 1 };
      return (
        (priority[left] ?? 10) - (priority[right] ?? 10) || left.localeCompare(right)
      );
    });
    const cases = variants.map((variant) => {
      if (variant.fields.length === 0) return `    case ${variant.caseName}`;
      return `    case ${variant.caseName}(\n${variant.fields
        .map((field) => `        ${swiftMember(field.property)}: ${field.type}`)
        .join(",\n")}\n    )`;
    });
    const decoding = variants
      .map((variant) => this.renderVariantDecode(variant))
      .join("\n");
    const encoding = variants
      .map((variant) => this.renderVariantEncode(variant))
      .join("\n");

    return `public enum ${name}: Codable, Equatable, Sendable {
${cases.join("\n")}

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        let kind = try container.decode(String.self, forKey: .kind)
${versioned ? "        let protocolVersion = try container.decode(CommaChatProtocolVersion.self, forKey: .protocolVersion)" : ""}

        switch kind {
${decoding}
        default:
            throw DecodingError.dataCorruptedError(
                forKey: .kind,
                in: container,
                debugDescription: "Unknown ${name} kind: \\(kind)"
            )
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)

        switch self {
${encoding}
        }
    }

    private enum CodingKeys: String, CodingKey {
${orderedKeys.map((key) => `        case ${swiftMember(key)} = "${key}"`).join("\n")}
    }
}`;
  }

  renderVariantDecode(variant) {
    const protocolVersionValidation =
      variant.protocolVersionCase === undefined
        ? []
        : [
            `            guard protocolVersion == .${variant.protocolVersionCase} else {
                throw DecodingError.dataCorruptedError(
                    forKey: .protocolVersion,
                    in: container,
                    debugDescription: "Unexpected protocolVersion \\(protocolVersion.rawValue) for ${variant.kind}; expected ${variant.protocolVersion}."
                )
            }`,
          ];
    const forbiddenValidation = variant.forbidden.flatMap((property) => {
      const member = swiftMember(property);
      return [
        `            guard !container.contains(.${member}) else {`,
        `                throw DecodingError.dataCorruptedError(`,
        `                    forKey: .${member},`,
        `                    in: container,`,
        `                    debugDescription: "${property} is not allowed for ${variant.kind}."`,
        `                )`,
        `            }`,
      ];
    });
    const constantValidation = variant.constants
      .filter(({ property }) => property !== "kind" && property !== "protocolVersion")
      .flatMap(({ constantCase, property, type }) => {
        const member = swiftMember(property);
        const local = `decoded${pascal(member)}`;
        return [
          `            let ${local} = try container.decode(${type}.self, forKey: .${member})`,
          `            guard ${local} == .${constantCase} else {`,
          `                throw DecodingError.dataCorruptedError(`,
          `                    forKey: .${member},`,
          `                    in: container,`,
          `                    debugDescription: "Unexpected constant value for ${property}."`,
          `                )`,
          `            }`,
        ];
      });
    const decodedArguments = variant.fields.map(
      (field) =>
        `                ${swiftMember(field.property)}: ${this.decodeExpression(field)}`
    );
    const assignment = decodedArguments.length
      ? `            self = .${variant.caseName}(\n${decodedArguments.join(",\n")}\n            )`
      : `            self = .${variant.caseName}`;
    return `        case ${JSON.stringify(variant.kind)}:
${[
  ...protocolVersionValidation,
  ...forbiddenValidation,
  ...constantValidation,
  assignment,
].join("\n")}`;
  }

  renderVariantEncode(variant) {
    const pattern = variant.fields.length
      ? `case let .${variant.caseName}(\n${variant.fields
          .map((field) => `            ${swiftMember(field.property)}`)
          .join(",\n")}\n        ):`
      : `case .${variant.caseName}:`;
    const writes = [
      ...(variant.protocolVersionCase === undefined
        ? []
        : [
            `            try container.encode(CommaChatProtocolVersion.${variant.protocolVersionCase}, forKey: .protocolVersion)`,
          ]),
      `            try container.encode(${JSON.stringify(variant.kind)}, forKey: .kind)`,
      ...variant.constants
        .filter(({ property }) => property !== "kind" && property !== "protocolVersion")
        .map(
          ({ property, type, constantCase }) =>
            `            try container.encode(${type}.${constantCase}, forKey: .${swiftMember(property)})`
        ),
      ...variant.fields.flatMap((field) => [
        ...this.renderEncodingValidation(field, "            "),
        `            try container.${field.required ? "encode" : "encodeIfPresent"}(${swiftMember(field.property)}, forKey: .${swiftMember(field.property)})`,
      ]),
    ];
    return `        ${pattern}
${writes.join("\n")}`;
  }

  variant(unionName, schema) {
    if (schema.type !== "object") {
      throw new Error(`${unionName} variants must be JSON objects.`);
    }
    const kind = schema.properties?.kind?.const;
    if (typeof kind !== "string") {
      throw new Error(`${unionName} variants must declare a string kind constant.`);
    }
    const required = new Set(schema.required ?? []);
    const protocolVersion = schema.properties?.protocolVersion?.const;
    const declaresProtocolVersion = schema.properties?.protocolVersion !== undefined;
    if (
      declaresProtocolVersion !== required.has("protocolVersion") ||
      (declaresProtocolVersion &&
        (!Number.isSafeInteger(protocolVersion) || protocolVersion < 1))
    ) {
      throw new Error(
        `${unionName} variant ${kind} must require a positive integer protocolVersion literal.`
      );
    }
    const contextName = variantContextName(kind);
    const constants = [];
    const fields = [];
    const forbidden = [];

    for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
      if (property === "kind" || property === "protocolVersion") continue;
      const resolved = this.resolve(propertySchema);
      if (isNeverSchema(resolved)) {
        forbidden.push(property);
        continue;
      }
      if (resolved.const !== undefined) {
        const field = this.field(contextName, property, resolved, true);
        constants.push({
          constantCase: field.constantCase,
          property,
          type: field.baseType,
        });
        continue;
      }
      fields.push(this.field(contextName, property, resolved, required.has(property)));
    }

    const sortedFields = fields.toSorted(
      (left, right) => fieldPriority(left.property) - fieldPriority(right.property)
    );
    return {
      caseName: caseNameForKind(kind),
      constants,
      fields: sortedFields,
      forbidden,
      kind,
      protocolVersion: declaresProtocolVersion ? protocolVersion : undefined,
      protocolVersionCase: declaresProtocolVersion ? `v${protocolVersion}` : undefined,
    };
  }

  field(parentName, property, schema, required) {
    const baseType = this.swiftType(schema, semanticTypeName(parentName, property), {
      parentName,
      property,
    });
    const resolved = this.resolve(schema);
    const constantCase =
      resolved.const !== undefined
        ? typeof resolved.const === "number" &&
          ["protocolVersion", "expectedProtocolVersion"].includes(property)
          ? `v${resolved.const}`
          : swiftCase(resolved.const)
        : undefined;
    return {
      baseType,
      constantCase,
      constraints: schemaConstraints(
        resolved,
        suggestedNameForError(parentName, property)
      ),
      property,
      required,
      type: required ? baseType : `${baseType}?`,
    };
  }

  decodeExpression(field) {
    const key = `.${swiftMember(field.property)}`;
    if (field.constraints?.kind === "string") {
      return `try CommaNativeContractValidation.${field.required ? "decodeString" : "decodeOptionalString"}(String.self, from: container, forKey: ${key}, minimumLength: ${swiftOptionalNumber(field.constraints.minimumLength)}, maximumLength: ${swiftOptionalNumber(field.constraints.maximumLength)})`;
    }
    if (field.constraints?.kind === "integer") {
      return `try CommaNativeContractValidation.${field.required ? "decodeInteger" : "decodeOptionalInteger"}(Int.self, from: container, forKey: ${key}, minimum: ${swiftOptionalNumber(field.constraints.minimum)}, maximum: ${swiftOptionalNumber(field.constraints.maximum)})`;
    }
    if (field.constraints?.kind === "number") {
      return `try CommaNativeContractValidation.${field.required ? "decodeNumber" : "decodeOptionalNumber"}(Double.self, from: container, forKey: ${key}, minimum: ${swiftOptionalNumber(field.constraints.minimum)}, maximum: ${swiftOptionalNumber(field.constraints.maximum)})`;
    }
    if (field.constraints?.kind === "array") {
      return `try CommaNativeContractValidation.${field.required ? "decodeArray" : "decodeOptionalArray"}(${field.baseType}.self, from: container, forKey: ${key}, minimumItems: ${swiftOptionalNumber(field.constraints.minimumItems)}, maximumItems: ${swiftOptionalNumber(field.constraints.maximumItems)})`;
    }
    if (!field.required) {
      return `try CommaNativeContractValidation.decodeOptional(${field.baseType}.self, from: container, forKey: ${key})`;
    }
    return `try container.decode(${field.baseType}.self, forKey: ${key})`;
  }

  renderConstantDecodingValidation(field, value, indentation = "        ") {
    if (!field.constantCase) return [];
    const member = swiftMember(field.property);
    return [
      `${indentation}guard ${value} == .${field.constantCase} else {`,
      `${indentation}    throw DecodingError.dataCorruptedError(`,
      `${indentation}        forKey: .${member},`,
      `${indentation}        in: container,`,
      `${indentation}        debugDescription: "Unexpected constant value for ${field.property}."`,
      `${indentation}    )`,
      `${indentation}}`,
    ];
  }

  renderConstantEncodingValidation(field, value, indentation = "        ") {
    if (!field.constantCase) return [];
    const member = swiftMember(field.property);
    return [
      `${indentation}guard ${value} == .${field.constantCase} else {`,
      `${indentation}    throw EncodingError.invalidValue(`,
      `${indentation}        ${value},`,
      `${indentation}        EncodingError.Context(`,
      `${indentation}            codingPath: container.codingPath + [CodingKeys.${member}],`,
      `${indentation}            debugDescription: "Unexpected constant value for ${field.property}."`,
      `${indentation}        )`,
      `${indentation}    )`,
      `${indentation}}`,
    ];
  }

  renderEncodingValidation(field, indentation = "        ") {
    if (!field.constraints) return [];
    const member = swiftMember(field.property);
    const value = field.required ? member : `value`;
    const method =
      field.constraints.kind === "string"
        ? "validateStringForEncoding"
        : field.constraints.kind === "integer"
          ? "validateIntegerForEncoding"
          : field.constraints.kind === "array"
            ? "validateArrayForEncoding"
            : "validateNumberForEncoding";
    const bounds =
      field.constraints.kind === "string"
        ? `minimumLength: ${swiftOptionalNumber(field.constraints.minimumLength)}, maximumLength: ${swiftOptionalNumber(field.constraints.maximumLength)}`
        : field.constraints.kind === "array"
          ? `minimumItems: ${swiftOptionalNumber(field.constraints.minimumItems)}, maximumItems: ${swiftOptionalNumber(field.constraints.maximumItems)}`
          : `minimum: ${swiftOptionalNumber(field.constraints.minimum)}, maximum: ${swiftOptionalNumber(field.constraints.maximum)}`;
    const validation = `${indentation}try CommaNativeContractValidation.${method}(${value}, ${bounds}, codingPath: container.codingPath + [CodingKeys.${member}])`;
    if (field.required) return [validation];
    return [
      `${indentation}if let value = ${member} {`,
      validation.replace(indentation, `${indentation}    `),
      `${indentation}}`,
    ];
  }

  swiftType(schema, suggestedName, context) {
    if (schema.$ref) {
      const referenceName = decodeURIComponent(schema.$ref.split("/").at(-1));
      this.register(referenceName, this.definitions[referenceName], {
        allowUnversionedUnion: true,
      });
      return referenceName;
    }
    const resolved = this.resolve(schema);
    if (resolved.const !== undefined) {
      if (
        typeof resolved.const === "number" &&
        ["protocolVersion", "expectedProtocolVersion"].includes(context.property)
      ) {
        this.ensureProtocolVersion();
        return "CommaChatProtocolVersion";
      }
      if (typeof resolved.const === "string") {
        this.registerInlineEnum(suggestedName, [resolved.const]);
        return suggestedName;
      }
    }
    if (resolved.enum && resolved.type === "string") {
      this.registerInlineEnum(suggestedName, resolved.enum);
      return suggestedName;
    }
    if (resolved.oneOf) {
      this.register(suggestedName, resolved, { allowUnversionedUnion: true });
      return suggestedName;
    }
    switch (resolved.type) {
      case "string":
        return "String";
      case "boolean":
        return "Bool";
      case "integer":
        return "Int";
      case "number":
        return "Double";
      case "array": {
        const itemName = semanticItemName(context.parentName, context.property);
        return `[${this.swiftType(resolved.items, itemName, {
          parentName: itemName,
          property: "item",
        })}]`;
      }
      case "object":
        this.register(suggestedName, resolved);
        return suggestedName;
      default:
        throw new Error(
          `Unsupported JSON Schema type ${String(resolved.type)} for ${suggestedName}.`
        );
    }
  }

  registerInlineEnum(name, values) {
    if (!this.declarations.has(name)) {
      this.declarations.set(name, this.renderStringEnum(name, values));
    }
  }

  resolve(schema) {
    if (!schema?.$ref) return schema;
    const name = decodeURIComponent(schema.$ref.split("/").at(-1));
    const resolved = this.definitions[name];
    if (!resolved) throw new Error(`Unresolved JSON Schema reference ${schema.$ref}.`);
    return resolved;
  }
}

