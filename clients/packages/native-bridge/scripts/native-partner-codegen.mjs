import { z } from "zod";

const schemaDraft = "https://json-schema.org/draft/2020-12/schema";
const schemaBaseURL = "https://comma.afk.surf/schemas/native-partner-contracts";

export function createNativePartnerJSONSchema(registry) {
  validateRegistry(registry);
  const definitions = {};
  const protocols = [];

  for (const leaf of registry.toSorted((left, right) =>
    left.id.localeCompare(right.id)
  )) {
    const schema = plainJSON(
      z.toJSONSchema(leaf.schema, {
        // Partner decoders mirror Zod's input semantics: unknown object keys
        // are accepted and then omitted from the parsed/re-encoded value.
        io: "input",
        reused: "inline",
        target: "draft-2020-12",
        unrepresentable: "throw",
      })
    );
    const localDefinitions = schema.$defs ?? {};
    delete schema.$defs;
    delete schema.$schema;

    mergeDefinitions(definitions, localDefinitions);
    mergeDefinitions(definitions, { [leaf.swiftType]: schema });
    protocols.push({
      direction: leaf.direction,
      id: leaf.id,
      schema: `#/$defs/${leaf.swiftType}`,
      swiftType: leaf.swiftType,
    });
  }

  const protocolVersions = collectProtocolVersions(definitions);
  const schemaVersionSuffix = protocolVersions.length
    ? protocolVersions.map((version) => `v${version}`).join("-")
    : "unversioned";

  return sortJSON({
    $defs: definitions,
    $id: `${schemaBaseURL}-${schemaVersionSuffix}.schema.json`,
    $schema: schemaDraft,
    anyOf: protocols.map(({ schema }) => ({ $ref: schema })),
    title: "Comma native partner contracts",
    "x-comma-native-protocols": protocols,
  });
}

function validateRegistry(registry) {
  const ids = new Set();
  const swiftTypes = new Set();
  for (const leaf of registry) {
    if (!leaf.id || ids.has(leaf.id)) {
      throw new Error(`Duplicate or empty native partner protocol id: ${leaf.id}`);
    }
    if (!/^[A-Z][A-Za-z0-9]*$/.test(leaf.swiftType) || swiftTypes.has(leaf.swiftType)) {
      throw new Error(
        `Duplicate or invalid native partner Swift type: ${leaf.swiftType}`
      );
    }
    ids.add(leaf.id);
    swiftTypes.add(leaf.swiftType);
  }
}

export function renderNativePartnerJSONSchema(registry) {
  return `${JSON.stringify(createNativePartnerJSONSchema(registry), null, 2)}\n`;
}

export function renderNativePartnerSwift(registry) {
  const bundle = createNativePartnerJSONSchema(registry);
  const renderer = new SwiftRenderer(bundle);

  if (renderer.protocolVersions.length > 0) {
    renderer.ensureProtocolVersion();
  }

  for (const leaf of registry) {
    renderer.register(leaf.swiftType, bundle.$defs[leaf.swiftType]);
  }

  return `// Generated by @comma/native-bridge/scripts/generate-native-partner-contracts.mjs.
// Do not edit by hand. Change the native partner leaf registry or its Zod schemas.

import Foundation

${renderSwiftValidationSupport()}

${renderer.render()}`;
}

export function nativePartnerProtocolManifest(registry) {
  return [...registry]
    .map(({ direction, id, swiftType }) => ({ direction, id, swiftType }))
    .toSorted((left, right) => left.id.localeCompare(right.id));
}

function plainJSON(value) {
  return JSON.parse(JSON.stringify(value));
}

function mergeDefinitions(target, additions) {
  for (const [name, schema] of Object.entries(additions)) {
    if (name in target && stableJSON(target[name]) !== stableJSON(schema)) {
      throw new Error(
        `Native partner schema definition ${name} has conflicting sources.`
      );
    }
    target[name] = schema;
  }
}

function sortJSON(value) {
  if (Array.isArray(value)) return value.map(sortJSON);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value)
      .toSorted(([left], [right]) => left.localeCompare(right))
      .map(([key, item]) => [key, sortJSON(item)])
  );
}

function stableJSON(value) {
  return JSON.stringify(sortJSON(value));
}

function isNeverSchema(schema) {
  return (
    schema?.not !== undefined &&
    schema.not !== null &&
    typeof schema.not === "object" &&
    Object.keys(schema.not).length === 0
  );
}

function collectProtocolVersions(value, versions = new Set()) {
  if (Array.isArray(value)) {
    for (const item of value) collectProtocolVersions(item, versions);
    return [...versions].toSorted((left, right) => left - right);
  }
  if (!value || typeof value !== "object") {
    return [...versions].toSorted((left, right) => left - right);
  }

  for (const [property, propertySchema] of Object.entries(value.properties ?? {})) {
    if (["protocolVersion", "expectedProtocolVersion"].includes(property)) {
      const version = propertySchema?.const;
      if (!Number.isSafeInteger(version) || version < 1) {
        throw new Error(
          `${property} must be a positive safe-integer literal in native partner schemas.`
        );
      }
      versions.add(version);
    }
  }
  for (const item of Object.values(value)) collectProtocolVersions(item, versions);
  return [...versions].toSorted((left, right) => left - right);
}

function schemaConstraints(schema, context) {
  if (schema?.type === "string") {
    for (const keyword of ["pattern", "format"]) {
      if (schema[keyword] !== undefined) {
        throw new Error(
          `Unsupported JSON Schema ${keyword} constraint for Swift field ${context}.`
        );
      }
    }
    const minimumLength = schema.minLength;
    const maximumLength = schema.maxLength;
    validateNonnegativeInteger(minimumLength, "minLength", context);
    validateNonnegativeInteger(maximumLength, "maxLength", context);
    if (minimumLength === undefined && maximumLength === undefined) return undefined;
    return { kind: "string", maximumLength, minimumLength };
  }

  if (["integer", "number"].includes(schema?.type)) {
    for (const keyword of ["exclusiveMinimum", "exclusiveMaximum", "multipleOf"]) {
      if (schema[keyword] !== undefined) {
        throw new Error(
          `Unsupported JSON Schema ${keyword} constraint for Swift field ${context}.`
        );
      }
    }
    const minimum = schema.minimum;
    const maximum = schema.maximum;
    validateFiniteNumber(minimum, "minimum", context);
    validateFiniteNumber(maximum, "maximum", context);
    if (minimum === undefined && maximum === undefined) return undefined;
    return { kind: schema.type, maximum, minimum };
  }

  if (schema?.type === "array") {
    const minimumItems = schema.minItems;
    const maximumItems = schema.maxItems;
    validateNonnegativeInteger(minimumItems, "minItems", context);
    validateNonnegativeInteger(maximumItems, "maxItems", context);
    if (schema.uniqueItems !== undefined) {
      throw new Error(
        `Unsupported JSON Schema uniqueItems constraint for Swift field ${context}.`
      );
    }
    if (minimumItems === undefined && maximumItems === undefined) return undefined;
    return { kind: "array", maximumItems, minimumItems };
  }

  for (const keyword of ["minItems", "maxItems", "uniqueItems"]) {
    if (schema?.[keyword] !== undefined) {
      throw new Error(
        `Unsupported JSON Schema ${keyword} constraint for Swift field ${context}.`
      );
    }
  }
  return undefined;
}

function validateNonnegativeInteger(value, keyword, context) {
  if (value === undefined) return;
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new Error(`${keyword} for Swift field ${context} must be nonnegative.`);
  }
}

function validateFiniteNumber(value, keyword, context) {
  if (value === undefined) return;
  if (!Number.isFinite(value)) {
    throw new Error(`${keyword} for Swift field ${context} must be finite.`);
  }
}

function swiftOptionalNumber(value) {
  return value === undefined ? "nil" : JSON.stringify(value);
}

function suggestedNameForError(parentName, property) {
  return `${parentName}.${property}`;
}

