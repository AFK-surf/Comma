function semanticTypeName(parentName, property) {
  if (property === "protocolVersion" || property === "expectedProtocolVersion") {
    return "CommaChatProtocolVersion";
  }
  if (property === "skills") return "CommaChatSkillReferenceList";
  return (
    semanticNames.get(`${parentName}.${property}`) ?? `${parentName}${pascal(property)}`
  );
}

function semanticItemName(parentName, property) {
  if (property === "skills") return "CommaChatSkillReference";
  return (
    semanticItemNames.get(`${parentName}.${property}`) ??
    `${parentName}${pascal(singular(property))}`
  );
}

function variantContextName(kind) {
  const known = {
    "chat.snapshot": "CommaChatSnapshotEnvelope",
    "command.result": "CommaSideChatCommandResult",
    "side-chat.protocol-error": "CommaSideChatProtocolError",
  };
  return known[kind] ?? `Comma${pascal(kind)}`;
}

function caseNameForKind(kind) {
  return swiftCase(kind.replace(/^(?:side-chat|chat|command)\./, ""));
}

function fieldPriority(property) {
  const priorities = {
    workspaceId: 0,
    conversationId: 1,
    requestId: 2,
  };
  return priorities[property] ?? 10;
}

function singular(value) {
  if (value.endsWith("ies")) return `${value.slice(0, -3)}y`;
  if (value.endsWith("s")) return value.slice(0, -1);
  return `${value}Item`;
}

function pascal(value) {
  return String(value)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("");
}

function swiftCase(value) {
  const parts = String(value)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  const identifier = parts
    .map((part, index) =>
      index === 0
        ? `${part[0].toLowerCase()}${part.slice(1)}`
        : `${part[0].toUpperCase()}${part.slice(1)}`
    )
    .join("");
  return swiftMember(identifier || "value");
}

function swiftMember(value) {
  const reserved = new Set([
    "associatedtype",
    "case",
    "class",
    "default",
    "deinit",
    "enum",
    "extension",
    "fileprivate",
    "func",
    "import",
    "init",
    "inout",
    "internal",
    "let",
    "operator",
    "private",
    "protocol",
    "public",
    "repeat",
    "static",
    "struct",
    "subscript",
    "typealias",
    "var",
    "where",
  ]);
  return reserved.has(value) ? `\`${value}\`` : value;
}
