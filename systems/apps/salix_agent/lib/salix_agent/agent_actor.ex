  @spec participant_realtime_snapshot(String.t(), String.t(), keyword()) ::
          {:ok, map()} | {:error, term()}
  def participant_realtime_snapshot(agent_id, session_id, opts \\ [])
      when is_binary(agent_id) and is_binary(session_id) and is_list(opts) do
    opts = Keyword.put_new(opts, :process_on_init, false)

    # Routing and the canonical activity read resolve the same control
    # record; one scope serves the snapshot from a single read.
    SalixStore.ReadScope.run(fn ->
      route_to_owner(agent_id, :participant_realtime_snapshot_local, [
        agent_id,
        session_id,
        opts
      ])
    end)
  end

  @doc false
