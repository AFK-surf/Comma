defmodule SalixAgent.AgentActor do
  @moduledoc """
  Owner-routed entry points for one agent's agent-level work.

  Every function resolves the agent owner node through AgentServer placement
  and runs its `_local` counterpart there. Work that must be ordered per agent
  goes to the agent's `SalixAgent.AgentRoleActor`; stateless session commands
  and configuration reads run in bounded reply tasks on the owner node.
  Distributed routing, leases, and placement belong to AgentServer; deliveries
  commit durably into session ledgers at deliver time (A2, rpc-direct-delivery.md).
  """

