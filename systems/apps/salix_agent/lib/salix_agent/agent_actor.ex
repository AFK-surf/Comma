      when is_binary(agent_id) and is_binary(session_id) do
    with {:ok, canonical} <- SalixAgent.Runtime.get_session_activity(agent_id, session_id) do
      {:ok,
       %{
         "canonical" => canonical,
         "activity" => SalixAgent.ActivitySurface.get_session(agent_id, session_id),
         "draft" => SalixAgent.DraftSurface.get(agent_id, session_id)
       }}
    end
  end

