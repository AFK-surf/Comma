  @spec wake_targets(String.t(), [wake_target()]) :: :ok | {:error, term()}
  def wake_targets(_agent_id, []), do: :ok

  def wake_targets(agent_id, targets) when is_binary(agent_id) and is_list(targets) do
    Enum.reduce(targets, :ok, fn target, first_error ->
      result = wake_target(agent_id, target)
      if first_error == :ok, do: result, else: first_error
    end)
  end

  defp wake_target(agent_id, %{runtime: :internal, session_id: session_id}),
    do: SalixAgent.InternalSessionFleet.wake(agent_id, session_id)

  defp wake_target(_agent_id, target), do: {:error, {:invalid_wake_target, target}}

  @spec wake_targets_after_commit(String.t(), [wake_target()]) ::
          :ok | {:deferred, term()} | {:error, term()}
  def wake_targets_after_commit(agent_id, targets)
      when is_binary(agent_id) and is_list(targets) do
    # A cutover can retire a target after recovery read its index. Classify
    # each target before aggregation so it cannot hide another wake failure.
    result =
      Enum.reduce(targets, :ok, fn target, first_error ->
        result =
          case wake_target(agent_id, target) do
            {:error, {:retired_router_session, _canonical}} -> :ok
            other -> other
          end

        if first_error == :ok, do: result, else: first_error
      end)

    case result do
      :ok ->
        :ok

      {:error, {:invalid_wake_target, _target} = reason} ->
        {:error, reason}

      {:error, reason} ->
        CommaLog.log("wake_targets_failed", %{
          agent_id: agent_id,
          targets: targets,
          reason: reason
        })

        {:deferred, reason}
    end
  end

  # Stateless commands need no ordering with the role actor. They run in a
  # bounded reply task on the owner node: the task is cancelled if the caller
  # exits and answers a timeout error after the configured reply budget.
  defp run_command(agent_id, opts, fun) do
    with {:ok, agent} <- SalixAgent.Control.get_record(agent_id),
         :ok <- require_role(agent) do
      AgentReplyTask.call(fn -> fun.(agent) end, Keyword.get(opts, :timeout, :infinity))
    end
  end

  defp require_role(%{"role" => role}) when role in @roles, do: :ok
  defp require_role(agent), do: {:error, {:unsupported_agent_role, agent["role"]}}

  defp require_role(%{"role" => role}, role), do: :ok
  defp require_role(agent, _role), do: {:error, {:unsupported_agent_role, agent["role"]}}

  defp route_to_owner(agent_id, local_fun, args) do
    opts = List.last(args)
    timeout = if is_list(opts), do: Keyword.get(opts, :timeout, :infinity), else: :infinity

    with {:ok, _agent} <- SalixAgent.Control.get_record(agent_id),
         :ok <- SalixAgent.Control.ensure_not_stopped(agent_id),
         {:ok, pid} <- SalixAgent.Placement.ensure_started(agent_id, owner_start_opts(opts)) do
      owner_node = SystemsRuntime.Proc.node(pid)

      if owner_node == SystemsRuntime.Proc.node() do
        apply(__MODULE__, local_fun, args)
      else
        :erpc.call(owner_node, __MODULE__, local_fun, args, timeout)
      end
    end
  end

  # :create defaults to false: every pre-A2 route_to_owner caller reaches an
  # agent whose Server already exists. The RPC delivery ingress passes
  # create: true (its contract default) so a first delivery can start the
  # owner Server, mirroring the staged path's wake.
  defp owner_start_opts(opts) when is_list(opts) do
    [create: Keyword.get(opts, :create, false), startup_mode: owner_startup_mode(opts)]
  end

  defp owner_start_opts(_opts), do: [create: false]

  defp owner_startup_mode(opts) do
    if Keyword.get(opts, :process_on_init, true), do: :active, else: :passive
  end

  defp start_actor(agent) do
    opts = [agent_id: agent["agent_id"], agent: agent]

    case SystemsRuntime.DynamicSupervisor.start_child(SalixAgent.FleetSup, {AgentRoleActor, opts}) do
      {:ok, pid} -> {:ok, pid}
      {:error, {:already_started, pid}} -> {:ok, pid}
      {:error, reason} -> {:error, reason}
    end
  catch
    :exit, reason -> {:error, {:exit, reason}}
  end
end
