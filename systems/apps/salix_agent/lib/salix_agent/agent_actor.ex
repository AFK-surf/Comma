    with {:ok, agent} <- SalixAgent.Control.get(agent_id, tenant_id),
         :ok <- require_role(agent, "router"),
         {:ok, pid} <- ensure_started(agent) do
      AgentRoleActor.switch_canonical_session(pid, expected_session_id, timeout)
    end
  end

  @doc """
  Read the exact Session Activity and transient presentation surfaces on the
  agent owner node.

  Activity and draft remain ephemeral owner-local state. Callers on a
  Conversation/Participant owner must route this snapshot instead of reading
  their own Pod's ETS tables. This owner-routed invalidation/read contract
  refines `tla/salix/ParticipantRealtimeSubscription.tla`.
