  def stage_delivery_and_wake_local(agent_id, entry, opts \\ [])
      when is_binary(agent_id) and is_map(entry) do
    case stage_delivery_local(agent_id, entry, opts) do
      {:ok, :committed, targets} = result ->
        case wake_targets_after_commit(agent_id, targets) do
          :ok -> result
          {:deferred, _reason} -> result
          {:error, _} = error -> error
        end

      other ->
        other
    end
  end

