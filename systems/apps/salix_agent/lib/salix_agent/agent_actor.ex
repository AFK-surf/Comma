  @doc false
  def stage_rpc_delivery_local(agent_id, entry, opts \\ [])
      when is_binary(agent_id) and is_map(entry) do
    with :ok <- verify_rpc_delivery_owner(agent_id) do
      stage_delivery_and_wake_local(agent_id, entry, opts)
    end
  end

  # The RPC delivery owner fence (plan §1.3): placement resolution and this
  # stage are not atomic, so before committing, the target node checks that
  # the DURABLE agent head still names it as owner. A moved head means this
  # node is stale — refuse with :not_owner and commit nothing; the caller
  # re-resolves placement (bounded, facade-side). An absent head is a
  # never-claimed agent: nobody owns it yet, and the first Server activation
  # on this node will claim it, so delivery may proceed. The residual
  # fence-read → CAS window is closed by the session CAS + the same-id retry
  # dedupe, modeled in tla/salix/RpcDeliver.tla.
  #
  # The head observation is the delivery's: inside its read scope the facade
  # (or the provider callback before it) may have read the head already,
  # and placement and this fence share that one read. An observation that
  # names another owner while this node holds a live claim predates that
  # claim (placement took the agent over from an expired lease after the
  # read); the fence then reads the head again instead of refusing a
  # delivery the durable head would admit. Placement returns once the Server
  # is registered, before its claim lands, so the fence first waits out a
  # local claim still in flight.
  defp verify_rpc_delivery_owner(agent_id) do
    case SalixStore.Agent.peek_in_scope(agent_id) do
      {:ok, head} ->
        cond do
          is_nil(head.owner_node) or head.owner_node == to_string(SystemsRuntime.Proc.node()) ->
            :ok

          local_claim_installed?(agent_id) ->
            SalixStore.ReadScope.invalidate({:head, agent_id})
            verify_rpc_delivery_owner_freshly(agent_id)

          true ->
            {:error, :not_owner}
        end

      {:error, :not_found} ->
        :ok

      {:error, _} = err ->
        err
    end
  end

  defp local_claim_installed?(agent_id) do
    :ok = SalixAgent.Fleet.await_ownership_installed(agent_id)
    match?({:ok, _epoch}, SalixAgent.OwnershipCell.fetch(agent_id))
  end

  defp verify_rpc_delivery_owner_freshly(agent_id) do
    case SalixStore.Agent.peek(agent_id) do
      {:ok, head} ->
        if is_nil(head.owner_node) or head.owner_node == to_string(SystemsRuntime.Proc.node()) do
          :ok
        else
          # This fresh head supersedes the local placement hint. Preserve any
          # newer claim installed while the read was in flight.
          SalixAgent.OwnershipCell.fence(agent_id, head.epoch)
          {:error, :not_owner}
        end

      {:error, :not_found} ->
        :ok

      {:error, _} = err ->
        err
    end
  end

  @spec stage_delivery(String.t(), inbox_entry(), keyword()) ::
          {:ok, :committed, [wake_target()]}
