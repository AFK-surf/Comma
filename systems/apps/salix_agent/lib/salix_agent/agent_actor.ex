  """
  @spec switch_router_session(String.t(), String.t(), String.t(), keyword()) ::
          {:ok, map()} | {:error, term()}
  def switch_router_session(agent_id, tenant_id, expected_session_id, opts \\ [])
      when is_binary(agent_id) and is_binary(tenant_id) and
             is_binary(expected_session_id) and is_list(opts) do
    with {:ok, _agent} <- SalixAgent.Control.get(agent_id, tenant_id) do
      route_to_owner(agent_id, :switch_router_session_local, [
        agent_id,
        tenant_id,
        expected_session_id,
        opts
      ])
    end
  end

  @doc false
